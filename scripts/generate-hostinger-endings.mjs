// Writes src/data/hostinger-endings.ts from Hostinger's own catalogue, so the app
// never offers an ending Hostinger doesn't sell. Run it by hand, with the token set
// in the environment, and commit the result:
//   HOSTINGER_API_TOKEN=... npm run data
import { writeFileSync } from "node:fs";
import { join } from "node:path";

const token = process.env.HOSTINGER_API_TOKEN;
if (!token) {
  console.error("Set HOSTINGER_API_TOKEN first.");
  process.exit(1);
}

const response = await fetch("https://developers.hostinger.com/api/billing/v1/catalog?category=DOMAIN", {
  headers: { authorization: `Bearer ${token}` },
});
if (!response.ok) {
  console.error(`Hostinger answered ${response.status}.`);
  process.exit(1);
}

// The catalogue also lists transfers, as ".COM Domain Transfer". Only new registrations count here.
const items = await response.json();
const endings = [...new Set(items.flatMap((item) => /^\.([A-Z0-9.-]+) Domain$/.exec(item.name)?.[1]?.toLowerCase() ?? []))].sort();
if (endings.length < 100) {
  console.error(`Only ${endings.length} endings came back, which looks wrong, so nothing was written.`);
  process.exit(1);
}

const lines = [];
for (let i = 0; i < endings.length; i += 12) {
  lines.push(`  ${endings.slice(i, i + 12).map((ending) => JSON.stringify(ending)).join(", ")},`);
}
const output = `// Generated by scripts/generate-hostinger-endings.mjs from Hostinger's catalogue. Never edit this by hand.
export const HOSTINGER_ENDINGS = [
${lines.join("\n")}
] as const;
`;
writeFileSync(join(import.meta.dirname, "..", "src/data/hostinger-endings.ts"), output);
console.log(`${endings.length} endings written.`);
